export function adminPageForPath(pathname: string) {
  const exact = ADMIN_PAGES.find(page => page.href === pathname);
  if (exact) return exact;
  const parent = [...ADMIN_PAGES].sort((a, b) => b.href.length - a.href.length).find(page => page.href !== "/admin" && pathname.startsWith(`${page.href}/`));
  return parent ? { ...parent, label: `${parent.label} · details` } : ADMIN_PAGES[0];
}
