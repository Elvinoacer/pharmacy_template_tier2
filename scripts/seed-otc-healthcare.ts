async function main() {
  console.log("Seeding all 14 OTC Healthcare categories and products...");

  // 1. Upsert categories
  for (const c of CATEGORIES) {
    await prisma.medicationCategory.upsert({
      where: { pharmacyId_slug: { pharmacyId: AFYVIA_ID, slug: c.slug } },
      create: {
        pharmacyId: AFYVIA_ID,
        slug: c.slug,
        name: c.name,
        description: c.description,
        imageUrl: c.imageUrl,
        brands: c.brands,
        tips: c.tips,
        publicVisible: true,
        active: true,
        sortOrder: c.sortOrder,
      },
      update: {
        name: c.name,
        description: c.description,
        imageUrl: c.imageUrl,
        brands: c.brands,
        tips: c.tips,
        publicVisible: true,
        active: true,
        sortOrder: c.sortOrder,
      },
    });
  }
  console.log(`Upserted ${CATEGORIES.length} medication categories.`);

  // Ensure default lookups exist
  const DEFAULT_LOOKUPS = [
    { kind: "dosage_form", value: "Tablet", slug: "tablet", sortOrder: 10 },
    { kind: "dosage_form", value: "Capsule", slug: "capsule", sortOrder: 20 },
    { kind: "dosage_form", value: "Syrup", slug: "syrup", sortOrder: 30 },
    { kind: "dosage_form", value: "Cream", slug: "cream", sortOrder: 40 },
    { kind: "dosage_form", value: "Gel", slug: "gel", sortOrder: 50 },
    { kind: "dosage_form", value: "Eye Drops", slug: "eye-drops", sortOrder: 60 },
    { kind: "dosage_form", value: "Nasal Spray", slug: "nasal-spray", sortOrder: 70 },
    { kind: "dosage_form", value: "Suspension", slug: "suspension", sortOrder: 80 },
    { kind: "dosage_form", value: "Sachet", slug: "sachet", sortOrder: 90 },
    { kind: "dosage_form", value: "Ointment", slug: "ointment", sortOrder: 100 },
    { kind: "dosage_form", value: "Inhaler", slug: "inhaler", sortOrder: 110 },
  ];
  for (const l of DEFAULT_LOOKUPS) {
    await prisma.medicationLookup.upsert({
      where: { kind_slug: { kind: l.kind as any, slug: l.slug } },
      create: { kind: l.kind as any, value: l.value, slug: l.slug, sortOrder: l.sortOrder, active: true },
      update: {},
    });
  }
  const allDosageForms = await prisma.medicationLookup.findMany({ where: { kind: "dosage_form" } });
  const tabletDf = allDosageForms.find((d) => d.slug === "tablet");

  // 2. Upsert master products and pharmacy inventory
  let createdCount = 0;
  for (const p of PRODUCTS) {
    // Determine dosageFormId from packSize/name/indications
    const desc = `${p.name} ${p.packSize} ${p.description}`.toLowerCase();
    const matchedDf = allDosageForms.find((df) => desc.includes(df.value.toLowerCase()) || desc.includes(df.slug)) || tabletDf;
    const dosageFormId = matchedDf?.id ?? null;

    // Check if master exists by barcode or slug
    let master = await prisma.medicationMaster.findFirst({
      where: { OR: [{ barcode: p.barcode }, { slug: p.slug }] },
    });

    if (!master) {
      master = await prisma.medicationMaster.create({
        data: {
          name: p.name,
          slug: p.slug,
          genericName: p.genericName,
          brandName: p.brandName || null,
          packSize: p.packSize,
          category: p.category,
          dosageFormId,
          description: p.description,
          indications: p.indications,
          dosage: p.dosage,
          sideEffects: p.sideEffects,
          contraindications: p.contraindications,
          storage: p.storage,
          imageUrl: p.imageUrl || null,
          barcode: p.barcode,
          controlledDrug: false,
          pediatricUse: p.pediatricUse || false,
        },
      });
    } else {
      master = await prisma.medicationMaster.update({
        where: { id: master.id },
        data: {
          name: p.name,
          genericName: p.genericName,
          brandName: p.brandName || null,
          packSize: p.packSize,
          category: p.category,
          description: p.description,
          indications: p.indications,
          dosage: p.dosage,
          sideEffects: p.sideEffects,
          contraindications: p.contraindications,
          storage: p.storage,
          imageUrl: p.imageUrl || master.imageUrl || null,
        },
      });
    }

    // Upsert PharmacyInventory
    const inv = await prisma.pharmacyInventory.upsert({
      where: { pharmacyId_slug: { pharmacyId: AFYVIA_ID, slug: p.slug } },
      create: {
        pharmacyId: AFYVIA_ID,
        medicationMasterId: master.id,
        slug: p.slug,
        sku: p.sku,
        price: p.price,
        currentStock: p.currentStock,
        lowStockThreshold: 5,
        shelfLocation: p.shelfLocation,
        overTheCounter: true,
        prescriptionRequired: false,
        publicListing: true,
        active: true,
      },
      update: {
        medicationMasterId: master.id,
        price: p.price,
        currentStock: p.currentStock,
        shelfLocation: p.shelfLocation,
        overTheCounter: true,
        prescriptionRequired: false,
        publicListing: true,
        active: true,
      },
    });

    // Ensure at least one active lot exists
    const lotExists = await prisma.inventoryLot.findFirst({
      where: { pharmacyInventoryId: inv.id },
    });

    if (!lotExists) {
      await prisma.inventoryLot.create({
        data: {
          pharmacyInventoryId: inv.id,
          batchNumber: `LOT-2026-${p.sku.replace(/[^A-Z0-9]/g, "")}`,
          expiryDate: new Date("2028-06-30"),
          quantity: p.currentStock,
          active: true,
        },
      });
    }

    createdCount++;
  }

  console.log(`Seeded ${createdCount} OTC products across all 14 categories.`);

  // 3. Update category aliases
  const aliasUpdates = [
    { from: "allergy", to: "allergy-treatments" },
    { from: "digestive", to: "digestive-health" },
    { from: "womens-health", to: "feminine-hygiene" },
    { from: "vitamins-supplements", to: "nutritional-products" },
  ];
  for (const a of aliasUpdates) {
    await prisma.medicationMaster
      .updateMany({ where: { category: a.from }, data: { category: a.to } })
      .catch(() => {});
  }

  console.log("Done! Platform now has 100% complete coverage for all 14 OTC Healthcare categories.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
